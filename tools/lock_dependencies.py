"""Resolve and hash-lock dependencies using pip's actual download report.

Run on the supported deployment platform (Linux amd64 / CPython 3.12).
No dependency installation or repository write permission is needed. All accepted
hashes come from pip's resolver/download metadata, never generated placeholders.
"""
from __future__ import annotations

import argparse
import base64
import json
from pathlib import Path
import platform
import re
import subprocess
import sys
import tempfile
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
NAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]*$")
VERSION = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.!+-]*$")


def resolve(source: Path, target: Path, constraints: Path | None = None) -> None:
    with tempfile.TemporaryDirectory(prefix="flight-alert-lock-") as tmp:
        report = Path(tmp) / "report.json"
        command = [sys.executable, "-m", "pip", "install", "--dry-run",
                   "--ignore-installed", "--disable-pip-version-check",
                   "--only-binary=:all:", "--report", str(report),
                   "--index-url", "https://pypi.org/simple", "-r", str(source)]
        if constraints:
            command.extend(["-c", str(constraints)])
        subprocess.run(command, check=True, cwd=ROOT)
        result = json.loads(report.read_text())
    entries = []
    for item in result["install"]:
        metadata = item["metadata"]
        name, version = metadata["name"], metadata["version"]
        download = item["download_info"]
        url = urlsplit(download["url"])
        digest = download.get("archive_info", {}).get("hashes", {}).get("sha256")
        if (not NAME.fullmatch(name) or not VERSION.fullmatch(version)
                or url.scheme != "https" or url.hostname != "files.pythonhosted.org"
                or not digest or not re.fullmatch(r"[0-9a-f]{64}", digest)):
            raise ValueError("Resolver returned unexpected dependency metadata")
        entries.append((name.lower().replace("_", "-"), name, version, digest))
    if not entries:
        raise ValueError("Empty dependency resolution")
    lines = ["# Generated by python -m tools.lock_dependencies",
             "# CPython 3.12 / Linux amd64 glibc wheel lock; supplement musl hashes before Alpine builds.",
             "# Install with: python -m pip install --require-hashes -r " + target.name]
    lines.extend(f"{name}=={version} --hash=sha256:{digest}"
                 for _, name, version, digest in sorted(entries))
    target.write_text("\n".join(lines) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--emit", action="store_true", help="Emit base64 locks for read-only CI retrieval")
    parser.add_argument("--scraper", action="store_true", help="Also resolve the optional scraper environment")
    args = parser.parse_args()
    if sys.version_info[:2] != (3, 12) or platform.system() != "Linux" or platform.machine() not in {"x86_64", "amd64"}:
        raise SystemExit("Generate deployment locks on Linux amd64 / CPython 3.12")
    resolve(ROOT / "requirements.in", ROOT / "requirements.txt")
    with tempfile.TemporaryDirectory(prefix="flight-alert-constraints-") as tmp:
        constraints = Path(tmp) / "runtime.txt"
        constraints.write_text("\n".join(line.split(" --hash=", 1)[0]
                              for line in (ROOT / "requirements.txt").read_text().splitlines()
                              if line and not line.startswith("#")) + "\n")
        resolve(ROOT / "requirements-dev.in", ROOT / "requirements-dev.txt", constraints)
        if args.scraper:
            resolve(ROOT / "requirements-scraper.in", ROOT / "requirements-scraper.txt", constraints)
    if args.emit:
        for path in sorted(ROOT.glob("requirements*.txt")):
            print("FLIGHT_ALERT_LOCK_BEGIN " + path.name)
            print(base64.b64encode(path.read_bytes()).decode("ascii"))
            print("FLIGHT_ALERT_LOCK_END " + path.name)


if __name__ == "__main__":
    main()
